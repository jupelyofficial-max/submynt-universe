import { feature } from "topojson-client";
import { geoPath, geoEquirectangular } from "d3-geo";
import worldData from "world-atlas/countries-110m.json" with { type: "json" };
import { writeFileSync } from "node:fs";

const W = 2048;
const H = 1024;

const geo = feature(worldData, worldData.objects.countries);

const projection = geoEquirectangular();
projection.fitSize([W, H], geo);

const path = geoPath(projection);

const scale = projection.scale();
const translate = projection.translate();

const paths = geo.features
  .map((f) => path(f))
  .filter(Boolean);

const combined = paths.join(" ");

const out = `// AUTO-GENERATED by scripts/gen-worldmap.mjs — do not hand-edit.
// World country outlines (Natural Earth 110m via world-atlas), projected with
// d3's geoEquirectangular into a ${W}x${H} texture space. SCALE/TRANSLATE are
// the exact projection constants — src/lib/geo.ts reimplements the same
// lng/lat -> x/y formula with these numbers so subscription node positions
// line up with the country shapes drawn from this path data.
export const WORLD_MAP_WIDTH = ${W};
export const WORLD_MAP_HEIGHT = ${H};
export const WORLD_MAP_SCALE = ${scale};
export const WORLD_MAP_TRANSLATE: [number, number] = [${translate[0]}, ${translate[1]}];
export const WORLD_MAP_PATH = "${combined}";
`;

writeFileSync(new URL("../src/data/worldMapPath.ts", import.meta.url), out);
console.log("wrote src/data/worldMapPath.ts");
console.log("scale", scale, "translate", translate);
console.log("bytes", out.length);
